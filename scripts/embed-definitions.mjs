#!/usr/bin/env node
// Regenerates the governed-definition data islands inside index.html from the
// authored files under definitions/. The authored files are the source of
// truth; the embedded copies are the runtime fallback so the app keeps
// working from file:// where fetch() is blocked (same pattern as the inline
// demo dataset). tests/unit/skills.test.mjs fails if the two drift — run this
// script after editing anything under definitions/.
//
// Usage: node scripts/embed-definitions.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEFS_DIR = path.join(ROOT, 'definitions');
const INDEX = path.join(ROOT, 'index.html');
const BEGIN = '<!-- BEGIN GOVERNED DEFINITIONS (generated by scripts/embed-definitions.mjs - do not edit by hand) -->';
const END = '<!-- END GOVERNED DEFINITIONS -->';

function walk(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

const files = walk(DEFS_DIR).map(p => path.relative(DEFS_DIR, p).split(path.sep).join('/'));
const islands = files.map(rel => {
  const content = fs.readFileSync(path.join(DEFS_DIR, rel), 'utf8');
  if (/<\/script/i.test(content)) {
    throw new Error(`definitions/${rel} contains "</script" which would break the embedded island.`);
  }
  return `<script type="text/plain" data-definition="${rel}">\n${content}</script>`;
}).join('\n');

const block = `${BEGIN}\n${islands}\n${END}`;

let html = fs.readFileSync(INDEX, 'utf8');
const beginIdx = html.indexOf(BEGIN);
const endIdx = html.indexOf(END);

if (beginIdx !== -1 && endIdx !== -1) {
  html = html.slice(0, beginIdx) + block + html.slice(endIdx + END.length);
} else {
  // First run: insert just before the demo dataset island.
  const anchor = '<script type="application/json" id="demoDataset">';
  const at = html.indexOf(anchor);
  if (at === -1) throw new Error('Could not find the demoDataset island to anchor the definitions block.');
  html = html.slice(0, at) + block + '\n' + html.slice(at);
}

fs.writeFileSync(INDEX, html);
console.log(`Embedded ${files.length} definition file(s) into index.html:\n  ` + files.join('\n  '));
